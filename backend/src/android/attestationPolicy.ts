import {
  SecurityLevel,
  VerifiedBootState,
  type AttestationRecord,
} from './keyDescription';

/**
 * Key origin value for keys generated inside the secure hardware.
 * {@link https://source.android.com/docs/security/features/keystore/tags#origin}
 */
const KEY_ORIGIN_GENERATED = 0;

/**
 * First attestation version (Keymaster 4) which includes the verified boot hash in the root of trust.
 */
const ATTESTATION_VERSION_WITH_BOOT_HASH = 3;

/**
 * Expected values of an Android key attestation.
 */
export type AttestationPolicy = {
  /** The expected attestation challenge. */
  challenge: string | Buffer;
  /** The allowed package names of the app. */
  packageNames: string[];
  /**
   * The allowed SHA-256 digests of the app signing certificates (hex, case insensitive).
   * When empty the check is skipped for devices running the stock OS, while devices running
   * an allowed self-signed OS are always rejected because the Play Integrity app recognition
   * verdict is not available for them.
   */
  signatureDigests: string[];
  /**
   * The allowed verified boot keys (hex, case insensitive) of the self-signed OS,
   * i.e. the GrapheneOS verified boot key fingerprints.
   */
  trustedSelfSignedBootKeys: ReadonlySet<string>;
};

/**
 * The operating system which has been verified:
 * - stock: the OS signed by the device manufacturer (verified boot state `Verified`);
 * - grapheneos: GrapheneOS (verified boot state `SelfSigned` with an allowed verified boot key).
 */
export type VerifiedOs = 'stock' | 'grapheneos';

/**
 * Error thrown when an attestation record doesn't satisfy the {@link AttestationPolicy}.
 */
export class AttestationPolicyError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'AttestationPolicyError';
  }
}

const normalizeHex = (value: string) => value.toLowerCase();

/**
 * Checks that the key attestation record satisfies the given policy.
 * This is the 7th step of the key attestation verification, which compares the attestation extension data
 * with the expected values, and it follows the GrapheneOS attestation compatibility guide:
 * the verified boot state must be either `Verified` or `SelfSigned` and, in the latter case,
 * the verified boot key must be one of the allowed ones. No patch level is enforced.
 * {@link https://developer.android.com/privacy-and-security/security-key-attestation#verifying}
 * {@link https://grapheneos.org/articles/attestation-compatibility-guide}
 * @param record - The parsed {@link AttestationRecord}.
 * @param policy - The {@link AttestationPolicy} to enforce.
 * @returns the {@link VerifiedOs} running on the device.
 * @throws {AttestationPolicyError} - If the record doesn't satisfy the policy.
 */
export const evaluateAttestationPolicy = (
  record: AttestationRecord,
  policy: AttestationPolicy
): VerifiedOs => {
  // Hardware backed attestation and key
  if (
    record.attestationSecurityLevel === SecurityLevel.software ||
    record.keymasterSecurityLevel === SecurityLevel.software
  ) {
    throw new AttestationPolicyError('Attestation is not hardware backed');
  }
  if (record.attestationSecurityLevel !== record.keymasterSecurityLevel) {
    throw new AttestationPolicyError(
      'Keymaster security level does not match attestation security level'
    );
  }

  // Replay protection
  const expectedChallenge = Buffer.isBuffer(policy.challenge)
    ? policy.challenge
    : Buffer.from(policy.challenge, 'utf-8');
  if (!record.attestationChallenge.equals(expectedChallenge)) {
    throw new AttestationPolicyError('Challenge mismatch');
  }

  if (record.origin !== KEY_ORIGIN_GENERATED) {
    throw new AttestationPolicyError(
      'Key has not been generated by the device'
    );
  }

  // App identity
  const applicationId = record.attestationApplicationId;
  if (!applicationId) {
    throw new AttestationPolicyError('Missing attestation application id');
  }
  if (
    !applicationId.packages.some((p) => policy.packageNames.includes(p.name))
  ) {
    throw new AttestationPolicyError(
      `Invalid package name: ${applicationId.packages.map((p) => p.name)}`
    );
  }
  const allowedDigests = new Set(policy.signatureDigests.map(normalizeHex));
  if (
    allowedDigests.size > 0 &&
    !applicationId.signatureDigests.some((d) =>
      allowedDigests.has(normalizeHex(d))
    )
  ) {
    throw new AttestationPolicyError('Invalid app signing certificate');
  }

  // Verified boot
  const rootOfTrust = record.rootOfTrust;
  if (!rootOfTrust) {
    throw new AttestationPolicyError('Missing root of trust');
  }
  if (!rootOfTrust.deviceLocked) {
    throw new AttestationPolicyError('Bootloader is unlocked');
  }
  if (
    record.attestationVersion >= ATTESTATION_VERSION_WITH_BOOT_HASH &&
    !rootOfTrust.verifiedBootHash
  ) {
    throw new AttestationPolicyError('Missing verified boot hash');
  }

  switch (rootOfTrust.verifiedBootState) {
    case VerifiedBootState.verified:
      return 'stock';
    case VerifiedBootState.selfSigned:
      if (allowedDigests.size === 0) {
        throw new AttestationPolicyError(
          'App signing certificate digests are required to accept a self-signed OS'
        );
      }
      if (
        !policy.trustedSelfSignedBootKeys.has(
          normalizeHex(rootOfTrust.verifiedBootKey)
        )
      ) {
        throw new AttestationPolicyError(
          `Verified boot key is not allowed: ${rootOfTrust.verifiedBootKey}`
        );
      }
      return 'grapheneos';
    default:
      throw new AttestationPolicyError(
        `Verified boot state is not verified or self-signed: ${rootOfTrust.verifiedBootState}`
      );
  }
};
